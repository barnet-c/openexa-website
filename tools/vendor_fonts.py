"""Self-host the site's three typefaces instead of loading them from Google Fonts.

Downloads the WOFF2 files Google Fonts serves for exactly the families, styles and weights the site uses (Instrument
Serif 400 roman + italic, Inter 400-600 as one variable file, IBM Plex Mono 400 + 500) in the latin and latin-ext
subsets, plus Inter's greek subset (Δ on Platform/Trust, Greek symbols in some blog posts), into site/assets/fonts/
with each family's SIL Open Font License, and writes the matching @font-face rules - the same unicode-range splits
and font-display: swap that Google's stylesheet used - between the fonts:start / fonts:end markers at the top of
site/assets/css/site.css. Rendering is unchanged; the gain is no third-party request chain (HTML -> site.css ->
fonts.googleapis.com -> fonts.gstatic.com) and no visitor IPs sent to Google.
Rerun only to update the fonts (needs network). Pages preload FONT_PRELOAD (see the page heads and the builders).
"""
import sys as _sys, os as _os
_sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))
from paths import REPO, SITE, DATA, SHOTS, DIST, ARCHIVE
import re, urllib.request
from pathlib import Path

CSS_URL = ("https://fonts.googleapis.com/css2?family=Instrument+Serif:ital@0;1"
           "&family=Inter:wght@400;500;600&family=IBM+Plex+Mono:wght@400;500&display=swap")
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/141.0.0.0 Safari/537.36"
KEEP = {"Instrument Serif": {"latin", "latin-ext"}, "Inter": {"latin", "latin-ext", "greek"},
        "IBM Plex Mono": {"latin", "latin-ext"}}
LICENSES = {"instrument-serif": "instrumentserif", "inter": "inter", "ibm-plex-mono": "ibmplexmono"}  # google/fonts ofl/<dir>
FONTS = Path(str(SITE)) / "assets" / "fonts"
CSS = Path(str(SITE)) / "assets" / "css" / "site.css"
START, END = "/* fonts:start (generated by tools/vendor_fonts.py) */", "/* fonts:end */"

def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=60) as r:
        return r.read()

faces = re.findall(r"/\* ([a-z-]+) \*/\s*@font-face \{(.*?)\}", get(CSS_URL).decode("utf-8"), re.S)
rules, files = {}, {}
for subset, body in faces:
    prop = dict(re.findall(r"\s*([a-z-]+): ([^;]+);", body))
    family = prop["font-family"].strip("'")
    if subset not in KEEP.get(family, ()): continue
    src = re.search(r"url\((https://[^)]+\.woff2)\)", prop["src"]).group(1)
    slug = family.lower().replace(" ", "-")
    # Inter is one variable file for every weight: Google repeats the same URL for 400/500/600
    style = "var" if family == "Inter" else prop["font-weight"] + ("i" if prop["font-style"] == "italic" else "")
    name = f"{slug}-{style}-{subset}.woff2"
    files[name] = src
    weight = "400 600" if family == "Inter" else prop["font-weight"]
    rules[name] = (f"@font-face {{ font-family: '{family}'; font-style: {prop['font-style']}; font-weight: {weight}; "
                   f"font-display: swap; src: url(../fonts/{name}) format('woff2'); unicode-range: {prop['unicode-range']}; }}")
assert len(files) == 11, sorted(files)

FONTS.mkdir(parents=True, exist_ok=True)
for name, src in sorted(files.items()):
    data = get(src)
    assert data[:4] == b"wOF2", name
    (FONTS / name).write_bytes(data)
    print(f"{name:42} {len(data):>7,} bytes")
for slug, d in LICENSES.items():
    (FONTS / f"OFL-{slug}.txt").write_bytes(get(f"https://raw.githubusercontent.com/google/fonts/main/ofl/{d}/OFL.txt"))

css = CSS.read_bytes().decode("utf-8")
nl = "\r\n" if "\r\n" in css else "\n"
block = nl.join([START] + [rules[n] for n in sorted(rules)] + [END])
if START in css:
    css = re.sub(re.escape(START) + ".*?" + re.escape(END), lambda m: block, css, count=1, flags=re.S)
else:
    css, hits = re.subn(r"@import url\('https://fonts\.googleapis\.com/[^']+'\);", lambda m: block, css, count=1)
    assert hits == 1, "no Google Fonts @import or fonts:start marker in site.css"
CSS.write_bytes(css.encode("utf-8"))
print(f"wrote {len(rules)} @font-face rules into site.css")
